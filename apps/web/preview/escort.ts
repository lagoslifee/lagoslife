import "@babylonjs/core/Meshes/instancedMesh";
import "@babylonjs/loaders/glTF";
import { Engine } from "@babylonjs/core/Engines/engine";
import { Scene } from "@babylonjs/core/scene";
import { FreeCamera } from "@babylonjs/core/Cameras/freeCamera";
import { HemisphericLight } from "@babylonjs/core/Lights/hemisphericLight";
import { DirectionalLight } from "@babylonjs/core/Lights/directionalLight";
import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import { Color4 } from "@babylonjs/core/Maths/math.color";
import { MeshBuilder } from "@babylonjs/core/Meshes/meshBuilder";
import { createMaterials } from "../src/game/materials";
import { VehicleFactory } from "../src/game/vehicles";
import { AvatarFactory } from "../src/game/avatar";
import { Escort } from "../src/game/escort";
const canvas = document.getElementById("c") as HTMLCanvasElement;
const engine = new Engine(canvas, true);
const scene = new Scene(engine);
scene.clearColor = new Color4(0.75, 0.82, 0.9, 1);
const p = new URLSearchParams(location.search);
const cam = new FreeCamera("cam", new Vector3(Number(p.get("x") ?? 6), Number(p.get("y") ?? 2.6), Number(p.get("z") ?? 8)), scene);
cam.setTarget(new Vector3(0, 1, Number(p.get("tz") ?? 3)));
new HemisphericLight("h", new Vector3(0.3, 1, -0.4), scene).intensity = 0.7;
new DirectionalLight("d", new Vector3(-0.5, -1, 0.3), scene).intensity = 2;
const materials = createMaterials(scene, "high" as never);
MeshBuilder.CreateGround("g", { width: 80, height: 80 }, scene);
const vehicles = await VehicleFactory.load(scene, materials as never, ["toyota-hilux"]);
const avatars = await AvatarFactory.load(scene);
const escort = new Escort("e", avatars, vehicles, () => 0, () => undefined, 4);
let z = -20;
const stopAt = Number(p.get("stop") ?? 14);
scene.onBeforeRenderObservable.add(() => {
  const dt = 1 / 30;
  if (z < stopAt) z += 0.4;
  escort.update(dt, { x: 0, z, yaw: 0, driving: p.get("walk") ? z < stopAt : true, outdoors: true });
});
engine.runRenderLoop(() => scene.render());
setTimeout(() => ((window as unknown as { ready: boolean }).ready = true), 6000);
