import "@babylonjs/core/Meshes/instancedMesh";
import "@babylonjs/loaders/glTF";
import { Engine } from "@babylonjs/core/Engines/engine";
import { Scene } from "@babylonjs/core/scene";
import { FreeCamera } from "@babylonjs/core/Cameras/freeCamera";
import { HemisphericLight } from "@babylonjs/core/Lights/hemisphericLight";
import { DirectionalLight } from "@babylonjs/core/Lights/directionalLight";
import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import { Color3, Color4 } from "@babylonjs/core/Maths/math.color";
import { MeshBuilder } from "@babylonjs/core/Meshes/meshBuilder";
import { StandardMaterial } from "@babylonjs/core/Materials/standardMaterial";
import { POLICE_CHECKPOINTS } from "@lagos-living/shared";
import { createMaterials } from "../src/game/materials";
import { VehicleFactory } from "../src/game/vehicles";
import { AvatarFactory } from "../src/game/avatar";
import { StreetCrews } from "../src/game/street-crews";
const canvas = document.getElementById("c") as HTMLCanvasElement;
const engine = new Engine(canvas, true);
const scene = new Scene(engine);
scene.clearColor = new Color4(0.75, 0.82, 0.9, 1);
const p = new URLSearchParams(location.search);
const site = POLICE_CHECKPOINTS[0]!;
const [px, pz] = site.point;
const f = [Math.sin(site.yaw), Math.cos(site.yaw)], r = [Math.cos(site.yaw), -Math.sin(site.yaw)];
const at = (fw: number, rt: number, y: number) => new Vector3(px + f[0]! * fw + r[0]! * rt, y, pz + f[1]! * fw + r[1]! * rt);
const cam = new FreeCamera("cam", at(Number(p.get("f") ?? -24), Number(p.get("r") ?? -2), Number(p.get("y") ?? 3)), scene);
cam.setTarget(at(Number(p.get("tf") ?? 0), Number(p.get("tr") ?? 3), 0.8));
cam.fov = 0.9;
new HemisphericLight("h", new Vector3(0.3, 1, -0.4), scene).intensity = 0.8;
new DirectionalLight("d", new Vector3(-0.5, -1, 0.3), scene).intensity = 1.6;
const materials = createMaterials(scene, "high" as never);
const road = MeshBuilder.CreateGround("road", { width: 9, height: 120 }, scene);
road.position.set(px, 0.005, pz); road.rotation.y = site.yaw;
const m = new StandardMaterial("asphalt", scene); m.diffuseColor = new Color3(0.2, 0.2, 0.22); road.material = m;
MeshBuilder.CreateGround("g", { width: 400, height: 400 }, scene).position.set(px, 0, pz);
const avatars = await AvatarFactory.load(scene);
const vehicles = await VehicleFactory.load(scene, materials as never, ["toyota-hilux", "toyota-corolla", "toyota-camry", "honda-accord", "lexus-rx350"]);
const crews = new StreetCrews(scene, avatars, vehicles, () => 0, () => {});
let t = 0;
scene.onBeforeRenderObservable.add(() => { const dt = engine.getDeltaTime() / 1000; t += dt; crews.update(Math.min(dt, 0.1), px, pz, true); });
engine.runRenderLoop(() => scene.render());
setTimeout(() => ((window as unknown as { ready: boolean }).ready = true), 5000);
