import "@babylonjs/loaders/glTF";
import { Engine } from "@babylonjs/core/Engines/engine";
import { Scene } from "@babylonjs/core/scene";
import { FreeCamera } from "@babylonjs/core/Cameras/freeCamera";
import { HemisphericLight } from "@babylonjs/core/Lights/hemisphericLight";
import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import { Color4 } from "@babylonjs/core/Maths/math.color";
import { INTERIOR_ORIGIN } from "@lagos-living/shared";
import { createMaterials } from "../src/game/materials";
import { SignAtlas } from "../src/game/sign-atlas";
import { buildTravelInterior } from "../src/game/travel-interiors";
const canvas = document.getElementById("c") as HTMLCanvasElement;
const engine = new Engine(canvas, true);
const scene = new Scene(engine);
scene.clearColor = new Color4(0.5, 0.6, 0.7, 1);
const p = new URLSearchParams(location.search);
const [ox, oz] = INTERIOR_ORIGIN;
const cam = new FreeCamera("cam", new Vector3(ox + Number(p.get("x") ?? 0), Number(p.get("y") ?? 1.7), oz + Number(p.get("z") ?? 0)), scene);
cam.setTarget(new Vector3(ox + Number(p.get("tx") ?? 0), Number(p.get("ty") ?? 1.5), oz + Number(p.get("tz") ?? -9)));
cam.fov = 1.0;
new HemisphericLight("h", new Vector3(0.3, 1, -0.4), scene).intensity = 0.4;
const materials = createMaterials(scene, "high" as never);
const atlas = new SignAtlas(scene, 1);
const trip = JSON.parse(p.get("trip") ?? "null");
const { PropLibrary } = await import("../src/game/props");
const props = p.get("props") ? await PropLibrary.load(scene) : null;
const view = buildTravelInterior(scene, materials as never, atlas, (p.get("kind") ?? "airport-dxb") as never, trip, props);
let t = 0;
scene.onBeforeRenderObservable.add(() => { t += engine.getDeltaTime() / 1000; (view as unknown as { update?: (t: number) => void }).update?.(t); });
engine.runRenderLoop(() => scene.render());
setTimeout(() => ((window as unknown as { ready: boolean }).ready = true), 2500);
import { EntranceMarkers } from "../src/game/entrance-markers";
import { travelSpot } from "@lagos-living/shared";
const guide = p.get("guide");
if (guide) {
  const markers = new EntranceMarkers(scene, () => 0);
  const point = travelSpot((p.get("kind") ?? "airport-dxb") as never, guide)!;
  scene.onBeforeRenderObservable.add(() => markers.update(engine.getDeltaTime() / 1000, [ox, oz], false, () => [], null, { key: guide, point, name: p.get("label") ?? guide, title: "NEXT STEP" }));
}
