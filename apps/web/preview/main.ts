import { Engine } from "@babylonjs/core/Engines/engine";
import { Scene } from "@babylonjs/core/scene";
import { FreeCamera } from "@babylonjs/core/Cameras/freeCamera";
import { HemisphericLight } from "@babylonjs/core/Lights/hemisphericLight";
import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import { createMaterials } from "../src/game/materials";
import { SignAtlas } from "../src/game/sign-atlas";
import { buildTravelInterior } from "../src/game/travel-interiors";
import { INTERIOR_ORIGIN } from "@lagos-living/shared";
const canvas = document.getElementById("c") as HTMLCanvasElement;
const engine = new Engine(canvas, true);
const scene = new Scene(engine);
const p = new URLSearchParams(location.search);
const [OX, OZ] = INTERIOR_ORIGIN as unknown as [number, number];
const cam = new FreeCamera("cam", new Vector3(OX + Number(p.get("x") ?? 0), Number(p.get("y") ?? 1.7), OZ + Number(p.get("z") ?? -8)), scene);
cam.setTarget(new Vector3(OX + Number(p.get("tx") ?? 0), Number(p.get("ty") ?? 3), OZ + Number(p.get("tz") ?? 10)));
cam.fov = 1.1;
new HemisphericLight("h", new Vector3(0.3, 1, -0.4), scene).intensity = 0.9;
const atlas = new SignAtlas(scene);
buildTravelInterior(scene, createMaterials(scene, "low" as never), atlas, (p.get("kind") ?? "airport-los") as never, null);
engine.runRenderLoop(() => scene.render());
setTimeout(() => ((window as unknown as { ready: boolean }).ready = true), 1500);
