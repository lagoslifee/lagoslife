import { Engine } from "@babylonjs/core/Engines/engine";
import { Scene } from "@babylonjs/core/scene";
import { TargetCamera } from "@babylonjs/core/Cameras/targetCamera";
import { HemisphericLight } from "@babylonjs/core/Lights/hemisphericLight";
import { DirectionalLight } from "@babylonjs/core/Lights/directionalLight";
import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import { Color3, Color4 } from "@babylonjs/core/Maths/math.color";
import { buildAirfield } from "../src/game/flight-scenes";
const canvas = document.getElementById("c") as HTMLCanvasElement;
const engine = new Engine(canvas, true);
const scene = new Scene(engine);
scene.clearColor = new Color4(0.74, 0.84, 0.93, 1);
scene.fogMode = Scene.FOGMODE_EXP2; scene.fogDensity = 0.0009; scene.fogColor = new Color3(0.78, 0.84, 0.88);
const p = new URLSearchParams(location.search);
const cam = new TargetCamera("cam", new Vector3(0, 5, 0), scene);
cam.fov = 0.62; cam.maxZ = 1600;
new HemisphericLight("h", new Vector3(0.3, 1, -0.4), scene).intensity = 0.7;
new DirectionalLight("d", new Vector3(-0.5, -1, 0.3), scene).intensity = 2;
const field = buildAirfield(scene, [5000, 8000], (p.get("a") ?? "los") as "los");
const t = Number(p.get("t") ?? 3);
const shot = p.get("mode") === "land" ? field.landing(t) : field.takeoff(t);
cam.position.copyFrom(shot.eye); cam.setTarget(shot.look);
engine.runRenderLoop(() => scene.render());
setTimeout(() => ((window as unknown as { ready: boolean }).ready = true), 2500);
