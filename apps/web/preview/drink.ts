import "@babylonjs/core/Meshes/instancedMesh";
import "@babylonjs/loaders/glTF";
import { Engine } from "@babylonjs/core/Engines/engine";
import { Scene } from "@babylonjs/core/scene";
import { FreeCamera } from "@babylonjs/core/Cameras/freeCamera";
import { HemisphericLight } from "@babylonjs/core/Lights/hemisphericLight";
import { DirectionalLight } from "@babylonjs/core/Lights/directionalLight";
import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import { Color4 } from "@babylonjs/core/Maths/math.color";
import { MeshBuilder } from "@babylonjs/core/Meshes/meshBuilder";
import { AvatarFactory } from "../src/game/avatar";
import { buildMenuItem } from "../src/game/drinks";
const canvas = document.getElementById("c") as HTMLCanvasElement;
const engine = new Engine(canvas, true);
const scene = new Scene(engine);
scene.clearColor = new Color4(0.75, 0.82, 0.9, 1);
const p = new URLSearchParams(location.search);
const cam = new FreeCamera("cam", new Vector3(Number(p.get("x") ?? 0.6), Number(p.get("y") ?? 1.45), Number(p.get("z") ?? 1.8)), scene);
cam.setTarget(new Vector3(Number(p.get("tx") ?? 0), Number(p.get("ty") ?? 1.15), 0));
new HemisphericLight("h", new Vector3(0.3, 1, 0.4), scene).intensity = 0.9;
new DirectionalLight("d", new Vector3(-0.5, -1, -0.6), scene).intensity = 1.5;
MeshBuilder.CreateGround("g", { width: 20, height: 20 }, scene);
const avatars = await AvatarFactory.load(scene);
const a = avatars.create("p", { body: "female", skinTone: "deep", hairstyle: "long", outfit: "corporate-red", accessory: "none" });
const item = buildMenuItem(scene, p.get("item") ?? "chapman");
a.hold(item);
const sip = p.get("sip") === "1";
scene.onBeforeRenderObservable.add(() => { if (sip) a.sip(5); a.update(0, (p.get("m") ?? "idle") as never, engine.getDeltaTime() / 1000); });
["chapman", "zobo", "malt", "energy-drink", "water", "small-chops", "suya"].forEach((id, i) => { const n = buildMenuItem(scene, id); n.position.set(1.2 + i * 0.25, 0.9, -0.3); });
MeshBuilder.CreateBox("table", { width: 2.2, height: 0.05, depth: 0.5 }, scene).position.set(1.95, 0.875, -0.3);
engine.runRenderLoop(() => scene.render());
setTimeout(() => ((window as unknown as { ready: boolean }).ready = true), 4000);
