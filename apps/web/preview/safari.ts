import "@babylonjs/core/Meshes/instancedMesh";
import "@babylonjs/loaders/glTF";
import { Engine } from "@babylonjs/core/Engines/engine";
import { Scene } from "@babylonjs/core/scene";
import { FreeCamera } from "@babylonjs/core/Cameras/freeCamera";
import { HemisphericLight } from "@babylonjs/core/Lights/hemisphericLight";
import { DirectionalLight } from "@babylonjs/core/Lights/directionalLight";
import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import { Color4 } from "@babylonjs/core/Maths/math.color";
import { EXCURSION_SEATS, INTERIOR_ORIGIN } from "@lagos-living/shared";
import { createMaterials } from "../src/game/materials";
import { SignAtlas } from "../src/game/sign-atlas";
import { buildTravelInterior, TRAVEL_SEAT_Y } from "../src/game/travel-interiors";
import { AvatarFactory } from "../src/game/avatar";
const canvas = document.getElementById("c") as HTMLCanvasElement;
const engine = new Engine(canvas, true);
const scene = new Scene(engine);
scene.clearColor = new Color4(0.62, 0.78, 0.92, 1);
const p = new URLSearchParams(location.search);
const [ox, oz] = INTERIOR_ORIGIN;
const cam = new FreeCamera("cam", new Vector3(ox + Number(p.get("x") ?? 4), Number(p.get("y") ?? 2.6), oz + Number(p.get("z") ?? 4)), scene);
cam.setTarget(new Vector3(ox + Number(p.get("tx") ?? 0), Number(p.get("ty") ?? 0.9), oz + Number(p.get("tz") ?? 0)));
cam.fov = 0.95;
cam.minZ = 0.05;
new HemisphericLight("h", new Vector3(0.3, 1, -0.4), scene).intensity = 0.6;
new DirectionalLight("d", new Vector3(-0.4, -1, -0.5), scene).intensity = 1.6;
const materials = createMaterials(scene, "high" as never);
const atlas = new SignAtlas(scene, 1);
const view = buildTravelInterior(scene, materials as never, atlas, (p.get("kind") ?? "safari") as never, null);
const avatars = await AvatarFactory.load(scene);
const riders = EXCURSION_SEATS.safari.slice(0, Number(p.get("n") ?? 3)).map((seat, index) => {
  const a = avatars.create(`r${index}`, { body: index % 2 ? "female" : "male", skinTone: "deep", hairstyle: index % 2 ? "braids" : "low-fade", outfit: index % 2 ? "resort-linen" : "polo-weekend", accessory: "none" });
  a.root.position.set(ox + seat.at[0], TRAVEL_SEAT_Y, oz + seat.at[1]);
  a.root.rotation.y = seat.yaw;
  return a;
});
let t = 0;
scene.onBeforeRenderObservable.add(() => {
  const dt = engine.getDeltaTime() / 1000;
  t += dt;
  view.update(t);
  for (const r of riders) r.update(0, "sit", dt);
});
engine.runRenderLoop(() => scene.render());
setTimeout(() => ((window as unknown as { ready: boolean }).ready = true), 4000);
