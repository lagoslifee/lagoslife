import { Engine } from "@babylonjs/core/Engines/engine";
import { Scene } from "@babylonjs/core/scene";
import { FreeCamera } from "@babylonjs/core/Cameras/freeCamera";
import { HemisphericLight } from "@babylonjs/core/Lights/hemisphericLight";
import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import { Color4 } from "@babylonjs/core/Maths/math.color";
import { MeshBuilder } from "@babylonjs/core/Meshes/meshBuilder";
import { EntranceMarkers } from "../src/game/entrance-markers";
import { buildExitDoor } from "../src/game/exit-door";
const canvas = document.getElementById("c") as HTMLCanvasElement;
const engine = new Engine(canvas, true);
const scene = new Scene(engine);
scene.clearColor = new Color4(0.55, 0.7, 0.85, 1);
const cam = new FreeCamera("cam", new Vector3(2, 2.2, -12), scene);
cam.setTarget(new Vector3(0, 2.2, 0));
new HemisphericLight("h", new Vector3(0.3, 1, -0.4), scene).intensity = 0.9;
MeshBuilder.CreateGround("g", { width: 60, height: 60 }, scene);
const wall = MeshBuilder.CreateBox("w", { width: 16, height: 8, depth: 1 }, scene); wall.position.set(0, 4, 1.2);
buildExitDoor(scene, 0, 0.7, Math.PI, [], { label: "Lekki Motors" });
const m = new EntranceMarkers(scene, () => 0);
const dest = { key: "x", point: [0, -0.6] as [number, number], name: "Lekki Motors" };
const others = [{ key: "y", point: [6, -0.6] as [number, number], name: "Chicken Republic" }, dest];
scene.onBeforeRenderObservable.add(() => m.update(engine.getDeltaTime() / 1000, [2, -12], true, () => others, null, dest));
engine.runRenderLoop(() => scene.render());
setTimeout(() => ((window as unknown as { ready: boolean }).ready = true), 2500);
