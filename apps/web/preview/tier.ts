import "@babylonjs/core/Meshes/instancedMesh";
import "@babylonjs/loaders/glTF";
import { Engine } from "@babylonjs/core/Engines/engine";
import { Scene } from "@babylonjs/core/scene";
import { FreeCamera } from "@babylonjs/core/Cameras/freeCamera";
import { HemisphericLight } from "@babylonjs/core/Lights/hemisphericLight";
import { DirectionalLight } from "@babylonjs/core/Lights/directionalLight";
import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import { Color4 } from "@babylonjs/core/Maths/math.color";
import { HOME_LAYOUTS, INTERIOR_ORIGIN } from "@lagos-living/shared";
import { createMaterials } from "../src/game/materials";
import { SignAtlas } from "../src/game/sign-atlas";
import { buildInterior, interiorModels } from "../src/game/interior";
import { PropLibrary } from "../src/game/props";
const canvas = document.getElementById("c") as HTMLCanvasElement;
const engine = new Engine(canvas, true);
const scene = new Scene(engine);
scene.clearColor = new Color4(0.05, 0.05, 0.05, 1);
const p = new URLSearchParams(location.search);
const [ox, oz] = INTERIOR_ORIGIN;
const cam = new FreeCamera("cam", new Vector3(ox + Number(p.get("x") ?? 0), Number(p.get("y") ?? 1.7), oz + Number(p.get("z") ?? -4)), scene);
cam.setTarget(new Vector3(ox + Number(p.get("tx") ?? 0), Number(p.get("ty") ?? 1.5), oz + Number(p.get("tz") ?? 5)));
cam.fov = Number(p.get("fov") ?? 1.15);
cam.maxZ = 200;
new DirectionalLight("sun", new Vector3(-0.45, -1, 0.32).normalize(), scene).intensity = 1.0;
new HemisphericLight("h", new Vector3(0, 1, 0), scene).intensity = 0.5;
const materials = createMaterials(scene, "high" as never);
const atlas = new SignAtlas(scene, 1);
const layout = HOME_LAYOUTS[(p.get("tier") ?? "mansion") as keyof typeof HOME_LAYOUTS];
const kind = (p.get("kind") ?? "preview") as "preview";
const props = await PropLibrary.load(scene, []);
await props.ensure(interiorModels(kind, layout, []));
const view = buildInterior(scene, materials as never, atlas, kind, "Ikoyi · Milverton Mansion", [], undefined, { layout, props });
console.log("spots", view.spots.map((s) => s.id).join(","));
engine.runRenderLoop(() => scene.render());
setTimeout(() => ((window as unknown as { ready: boolean }).ready = true), 4000);
