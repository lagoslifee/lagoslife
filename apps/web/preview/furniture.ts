import "@babylonjs/loaders/glTF";
import { Engine } from "@babylonjs/core/Engines/engine";
import { Scene } from "@babylonjs/core/scene";
import { FreeCamera } from "@babylonjs/core/Cameras/freeCamera";
import { HemisphericLight } from "@babylonjs/core/Lights/hemisphericLight";
import { DirectionalLight } from "@babylonjs/core/Lights/directionalLight";
import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import { Color4 } from "@babylonjs/core/Maths/math.color";
import { MeshBuilder } from "@babylonjs/core/Meshes/meshBuilder";
import { PropLibrary } from "../src/game/props";
const canvas = document.getElementById("c") as HTMLCanvasElement;
const engine = new Engine(canvas, true);
const scene = new Scene(engine);
scene.clearColor = new Color4(0.6, 0.65, 0.7, 1);
const p = new URLSearchParams(location.search);
const ids = (p.get("ids") ?? "").split(",");
const cols = Number(p.get("cols") ?? 4);
const gap = Number(p.get("gap") ?? 3.4);
const cam = new FreeCamera("cam", new Vector3(((cols - 1) * gap) / 2, Number(p.get("y") ?? 5), Number(p.get("z") ?? 9)), scene);
cam.setTarget(new Vector3(((cols - 1) * gap) / 2, 0.6, -((Math.ceil(ids.length / cols) - 1) * gap) / 2));
cam.fov = 0.9;
new HemisphericLight("h", new Vector3(0.3, 1, 0.4), scene).intensity = 0.9;
new DirectionalLight("d", new Vector3(-0.3, -1, -0.6), scene).intensity = 1.2;
MeshBuilder.CreateGround("g", { width: 60, height: 60 }, scene);
const lib = await PropLibrary.load(scene, ids as never);
ids.forEach((id, i) => {
  const x = (i % cols) * gap, z = -Math.floor(i / cols) * gap;
  lib.place(id as never, x, z, 0, []);
  const m = MeshBuilder.CreateBox("m", { width: 0.1, height: 0.05, depth: 0.5 }, scene); m.position.set(x - 1.4, 0.03, z + 1.2);
});
engine.runRenderLoop(() => scene.render());
setTimeout(() => ((window as unknown as { ready: boolean }).ready = true), 3000);
