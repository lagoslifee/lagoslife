import "@babylonjs/core/Meshes/instancedMesh";
import "@babylonjs/loaders/glTF";
import { Engine } from "@babylonjs/core/Engines/engine";
import { Scene } from "@babylonjs/core/scene";
import { FreeCamera } from "@babylonjs/core/Cameras/freeCamera";
import { HemisphericLight } from "@babylonjs/core/Lights/hemisphericLight";
import { DirectionalLight } from "@babylonjs/core/Lights/directionalLight";
import { Vector3 } from "@babylonjs/core/Maths/math.vector";
import { Color4 } from "@babylonjs/core/Maths/math.color";
import { MeshBuilder } from "@babylonjs/core/Meshes/meshBuilder";
import { PLOTS } from "@lagos-living/shared";
import { createMaterials } from "../src/game/materials";
import { PlotsView } from "../src/game/plots";
import { PropLibrary } from "../src/game/props";
const canvas = document.getElementById("c") as HTMLCanvasElement;
const engine = new Engine(canvas, true);
const scene = new Scene(engine);
scene.clearColor = new Color4(0.55, 0.7, 0.85, 1);
const p = new URLSearchParams(location.search);
const plot = PLOTS[Number(p.get("plot") ?? 0)]!;
const at = (a: number, n: number, y: number) => new Vector3(plot.center[0] + plot.along[0] * a + plot.inward[0] * n, y, plot.center[1] + plot.along[1] * a + plot.inward[1] * n);
const cam = new FreeCamera("cam", at(Number(p.get("a") ?? 14), Number(p.get("n") ?? -24), Number(p.get("y") ?? 14)), scene);
cam.setTarget(at(Number(p.get("ta") ?? 0), Number(p.get("tn") ?? 2), Number(p.get("ty") ?? 4)));
cam.fov = Number(p.get("fov") ?? 0.9);
cam.maxZ = 500;
new DirectionalLight("sun", new Vector3(-0.45, -1, 0.32).normalize(), scene).intensity = 2.2;
new HemisphericLight("h", new Vector3(0, 1, 0), scene).intensity = 0.9;
const materials = createMaterials(scene, "high" as never);
const ground = MeshBuilder.CreateGround("g", { width: 400, height: 400 }, scene);
ground.position.set(plot.center[0], -0.02, plot.center[1]);
ground.material = materials.asphalt;
const view = new PlotsView(scene, materials as never, () => 0, () => undefined);
const design = p.get("design") ?? "helipad-mansion";
const done = { stagesPaid: 4, stageStartedAt: new Date(0).toISOString(), stageReadyAt: new Date(0).toISOString(), completed: true, homeId: `built-${plot.id}` };
const states = PLOTS.map((entry) => ({ id: entry.id, status: "mine", tenureType: "owned", nextPaymentAt: null, accessEndsAt: null, overdue: false,
  construction: entry === plot && design !== "shop" ? { designId: design, ...done } : null,
  business: entry === plot && design === "shop" ? { type: p.get("type") ?? "buka", name: p.get("name") ?? "Iya Basira Kitchen" } : null }));
view.update(states as never, Date.now());
if (p.get("props") !== "0") view.setProps(await PropLibrary.load(scene, []));
engine.runRenderLoop(() => scene.render());
setTimeout(() => ((window as unknown as { ready: boolean }).ready = true), 5000);
