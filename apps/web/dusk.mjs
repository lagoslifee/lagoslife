import { chromium } from "@playwright/test";
const browser = await chromium.launch({ args: ["--use-gl=swiftshader", "--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1100, height: 700 } });
page.on("pageerror", (e) => console.log("ERR", e.message));
const theme = process.env.THEME ?? "dark";
await page.addInitScript((t) => localStorage.setItem("lagos-theme", t), theme);
await page.goto("http://localhost:5183/");
await page.getByRole("button", { name: /Collect/ }).click({ timeout: 60000 }).catch(() => {});
await page.waitForTimeout(1000);
await page.getByText(/decide later/).click().catch(() => {});
await page.keyboard.press("p");
await page.waitForTimeout(1500);
await page.getByRole("button", { name: /Settings/ }).first().click().catch((e) => console.log("noset", e.message));
await page.waitForTimeout(1000);
await page.locator(`.theme-option.${theme}`).click().catch((e) => console.log("notheme", e.message));
await page.waitForTimeout(800);
await page.keyboard.press("Escape");
await page.waitForTimeout(6000);
await page.screenshot({ path: `/tmp/dusk-${theme}.png` });
await browser.close();
